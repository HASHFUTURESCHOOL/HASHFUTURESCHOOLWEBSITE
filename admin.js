async function loadPosts() {
  const { posts } = await api('/api/admin/posts');
  state.posts = posts;
  $('#count-posts').textContent = posts.length;
  renderPosts();
}

function renderPosts() {
  const list = $('#posts-list');
  if (!state.posts.length) {
    list.innerHTML = '<div class="empty">No posts yet. Create your first post.</div>';
    return;
  }
  list.innerHTML = state.posts
    .map((p) => {
      const statusBadge = p.published ? 'published' : 'draft';
      const aiBadge = p.source === 'ai'
        ? '<span class="badge ai" title="Generated by AI">AI</span> '
        : '';
      const publishBtn = p.published
        ? '<button class="btn btn-sm btn-ghost" data-unpublish="' + p.id + '">Unpublish</button>'
        : '<button class="btn btn-sm btn-success" data-publish="' + p.id + '">' + (p.source === 'ai' ? 'Approve & Publish' : 'Publish') + '</button>';
      return `
        <div class="card">
          <div class="meta">
            <div class="title">${aiBadge}${escapeHtml(p.title)}</div>
            <div class="sub">${escapeHtml(p.category || 'Uncategorized')} · Updated ${formatDate(p.updated_at)}</div>
          </div>
          <div style="display:flex;align-items:center;gap:12px;">
            <span class="badge ${statusBadge}">${p.published ? 'Published' : 'Draft'}</span>
            <div class="row-actions">
              <button class="btn btn-sm btn-ghost" data-edit="${p.id}">Edit</button>
              ${publishBtn}
              <button class="btn btn-sm btn-danger" data-delete="${p.id}">Delete</button>
            </div>
          </div>
        </div>`;
    })
    .join('');

  $$('[data-edit]').forEach((btn) =>
    btn.addEventListener('click', () => openPostEditor(Number(btn.dataset.edit)))
  );
  $$('[data-publish]').forEach((btn) =>
    btn.addEventListener('click', () => setPublished(Number(btn.dataset.publish), true))
  );
  $$('[data-unpublish]').forEach((btn) =>
    btn.addEventListener('click', () => setPublished(Number(btn.dataset.unpublish), false))
  );
  $$('[data-delete]').forEach((btn) =>
    btn.addEventListener('click', () => deletePost(Number(btn.dataset.delete)))
  );
}

