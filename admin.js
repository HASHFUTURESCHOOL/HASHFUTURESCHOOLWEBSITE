// ---------- Newsletter ----------
async function loadNewsletter() {
  try {
    state.newsletter = await api('/api/admin/newsletter');
    renderNewsletter();
  } catch (err) {
    flash(err.message, 'error');
  }
}

function renderNewsletter() {
  const { content, campaigns, stats } = state.newsletter;
  const subjectEl = $('#nl-subject');
  const bodyEl = $('#nl-body');
  const countEl = $('#nl-active-count');
  const statusEl = $('#nl-status');

  if (subjectEl) subjectEl.value = content?.subject || '';
  if (bodyEl) bodyEl.value = content?.bodyMd || '';
  if (countEl) countEl.value = String(stats?.activeSubscribers ?? 0);
  if (statusEl) {
    statusEl.textContent = state.newsletter.hasProvider
      ? '✅ Provider ready'
      : '⚠️ MAILGUN_API_KEY not set';
    statusEl.className = 'pill ' + (state.newsletter.hasProvider ? 'ok' : 'warn');
  }

  const list = $('#nl-campaigns');
  if (!list) return;
  if (!campaigns || !campaigns.length) {
    list.innerHTML = '<div class="empty">No sends yet. Click “Send Now” to deliver your first weekly newsletter.</div>';
    return;
  }

  list.innerHTML = campaigns
    .map((c) => {
      const badgeClass =
        c.status === 'sent' ? 'published'
        : c.status === 'failed' ? 'unsubscribed'
        : c.status === 'partial' ? 'draft'
        : 'unsubscribed';
      return `
        <div class="card">
          <div class="meta">
            <div class="title">${escapeHtml(c.subject)}</div>
            <div class="sub">${formatDate(c.createdAt)} · ${escapeHtml(c.trigger)}</div>
          </div>
          <div style="display:flex;align-items:center;gap:12px;">
            <span class="badge ${badgeClass}">${escapeHtml(c.status)}</span>
            <div class="sub" style="margin-left:auto;">${c.recipientCount} to · ${c.sentCount} sent · ${c.failedCount} failed</div>
          </div>
        </div>`;
    })
    .join('');
}

